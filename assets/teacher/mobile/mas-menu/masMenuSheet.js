const SVG_MOON  = `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z"/></svg>`;
const SVG_SUN   = `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><circle cx="12" cy="12" r="5"/><line x1="12" y1="1" x2="12" y2="3"/><line x1="12" y1="21" x2="12" y2="23"/><line x1="4.22" y1="4.22" x2="5.64" y2="5.64"/><line x1="18.36" y1="18.36" x2="19.78" y2="19.78"/><line x1="1" y1="12" x2="3" y2="12"/><line x1="21" y1="12" x2="23" y2="12"/><line x1="4.22" y1="19.78" x2="5.64" y2="18.36"/><line x1="18.36" y1="5.64" x2="19.78" y2="4.22"/></svg>`;

export function renderMasMenu({ contentEl, onOpenPerfil, onOpenWeights, onClose }) {
  function draw() {
    const isLight = getTheme() === "light";
    contentEl.innerHTML = `
      <div class="mt-sheet-header">
        <span class="mt-sheet-title">Más</span>
        <button class="mt-sheet-close" id="mmClose" aria-label="Cerrar">${SVG_CLOSE}</button>
      </div>
      <div class="mt-sheet-body">
        <button class="mt-mas-item" type="button" id="mmPerfil">${SVG_USER}<span>Mi perfil</span></button>
        <button class="mt-mas-item" type="button" id="mmWeights">${SVG_GEAR}<span>Configurar pesos</span></button>
        <button class="mt-mas-item" type="button" id="mmTheme">
          ${isLight ? SVG_MOON : SVG_SUN}<span>Modo ${isLight ? "oscuro" : "claro"}</span>
        </button>
      </div>`;

    contentEl.querySelector("#mmClose").addEventListener("click", onClose);
    contentEl.querySelector("#mmPerfil").addEventListener("click", onOpenPerfil);
    contentEl.querySelector("#mmWeights").addEventListener("click", onOpenWeights);
    contentEl.querySelector("#mmTheme").addEventListener("click", () => {
      saveTheme(isLight ? "dark" : "light");
      draw();
    });
  }

  draw();
}
